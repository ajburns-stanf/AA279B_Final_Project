function col = plot_style(target)
% Set paper-ready plot defaults: Okabe-Ito colors, LaTeX text, large fonts
% Inputs: target - figure to style (optional, default groot styles every new figure this session)
% Outputs: col - Okabe-Ito RGB colors by name (col.blue, ...), col.order - all eight as rows (8x3)
    if nargin < 1, target = groot; end

    names = {'black', 'orange', 'skyblue', 'green', 'yellow', 'blue', 'vermillion', 'purple'};
    hex   = {'000000', 'E69F00', '56B4E9', '009E73', 'F0E442', '0072B2', 'D55E00', 'CC79A7'};
    for k = 1:numel(names)
        col.(names{k}) = hex2dec(reshape(hex{k}, 2, []).').'/255;
    end
    col.order = cell2mat(cellfun(@(n) col.(n), names.', 'UniformOutput', false));

    % Font sizes: text 17, labels 19, titles 20, ticks and legend 15
    set(target, ...
        'defaultTextInterpreter', 'latex', ...
        'defaultAxesTickLabelInterpreter', 'latex', ...
        'defaultLegendInterpreter', 'latex', ...
        'defaultColorbarTickLabelInterpreter', 'latex', ...
        'defaultTextFontSize', 17, ...
        'defaultAxesFontSize', 15, ...
        'defaultAxesLabelFontSizeMultiplier', 19/15, ...
        'defaultAxesTitleFontSizeMultiplier', 20/15, ...
        'defaultLegendFontSizeMode', 'manual', ...
        'defaultLegendFontSize', 15, ...
        'defaultColorbarFontSizeMode', 'manual', ...
        'defaultColorbarFontSize', 15, ...
        'defaultAxesColorOrder', col.order, ...
        'defaultLineLineWidth', 1.5, ...
        'defaultAxesBox', 'on');

    if isgraphics(target, 'figure')
        target.Color = 'w';
    else
        set(target, 'defaultFigureColor', 'w');
    end
end
